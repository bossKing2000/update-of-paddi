-- Phase 1E: store the active role per session instead of relying only on the
-- account-wide User.role.
--
-- Nullable and additive on purpose:
--   * Existing sessions keep NULL and are treated as "act as the account role",
--     so the deploy needs no backfill, no data migration and no forced logout.
--   * Nothing is NOT NULL and no default is written, because a default would
--     silently pin every pre-existing session to one role at migration time.
--
-- No index is added: sessions are only ever looked up by `sessionId`
-- (unique) or by `userId` (already indexed below), and the new column is read
-- as part of a row that is already being fetched. Adding an index here would
-- be cost without a query to serve.
ALTER TABLE "UserSession" ADD COLUMN "activeRole" "Role";