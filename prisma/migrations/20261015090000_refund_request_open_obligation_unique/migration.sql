-- C-2: enforce at most one OPEN refund obligation per (paymentRef, orderId).
--
-- Refund obligations are filed by three independent writers: paid-order
-- cancellation (src/controllers/orderController.ts), the vendor-confirmation
-- timeout worker, and payment finalization
-- (src/services/paymentFinaligation / paymentFinalizer.service.ts). Each one
-- used to look for an open obligation and insert one if it found none. Under
-- PostgreSQL's default READ COMMITTED isolation that read-then-create is not
-- atomic, so two concurrent operations could both observe "no open
-- obligation" and both insert — leaving duplicate open refund obligations for
-- the same order.
--
-- This is an additive index only. No columns, rows, or existing constraints
-- are modified.
--
-- Why a PARTIAL unique index and not a plain UNIQUE (paymentRef, orderId):
-- a plain two-column unique constraint would apply to every row regardless of
-- status, so once an obligation reached a terminal status (COMPLETED, FAILED,
-- or REJECTED) the historical row would permanently block any later refund
-- obligation for that same order. That contradicts the intended behaviour:
-- only PENDING/APPROVED/PROCESSING obligations hold a reservation, and a
-- terminal one must not block a re-request. The partial predicate is what
-- gives us both guarantees at once.
--
-- "orderId" is excluded from the index by the IS NOT NULL predicate on
-- purpose. It is nullable with no backfill: historical and batch-level
-- (multi-order payment) refund requests intentionally remain NULL, and the
-- customer-facing refund guard is deliberately payment-wide. Such rows are
-- not per-order obligations and must not be constrained here.
--
-- !! DEPLOYMENT ORDER — READ BEFORE SHIPPING CODE !!
-- This migration MUST be applied successfully BEFORE deploying the code that
-- uses the targeted `INSERT ... ON CONFLICT ("paymentRef","orderId") WHERE ...
-- DO NOTHING` in src/services/refundObligation.service.ts. Without this index
-- PostgreSQL raises SQLSTATE 42P10 ("there is no unique or exclusion
-- constraint matching the ON CONFLICT specification") and ALL THREE
-- refund-obligation creation paths fail outright:
--   - src/controllers/orderController.ts      (paid-order cancellation)
--   - src/jobs/workers jobs/expireUnconfirmedVendorOrders.ts (timeout worker)
--   - src/services/paymentFinalizer.service.ts (payment finalization)
-- That is a hard failure, not a degradation: without the index the obligation
-- is never filed and the surrounding operation errors. Apply first, then deploy.
-- This migration has NOT been applied or verified anywhere.
--
-- PRE-MIGRATION PREFLIGHT (run against the intended target first):
--   SELECT "paymentRef","orderId",count(*) FROM "RefundRequest"
--   WHERE "orderId" IS NOT NULL
--     AND status IN ('PENDING','APPROVED','PROCESSING')
--   GROUP BY 1,2 HAVING count(*)>1;
-- If this returns any rows, STOP. The index cannot be created while
-- duplicates exist, and picking a surviving row is a business decision
-- (a duplicate may already have been refunded at Paystack). Do not delete
-- rows automatically.
--
-- Prisma 6.19.2 cannot express a partial index in schema.prisma, so this
-- constraint exists only here. `prisma migrate diff` against a live database
-- may report drift for it, and `prisma db push` will not recreate it.
--
-- Rollback: DROP INDEX "RefundRequest_open_obligation_per_order";
CREATE UNIQUE INDEX "RefundRequest_open_obligation_per_order"
  ON "RefundRequest" ("paymentRef", "orderId")
  WHERE "orderId" IS NOT NULL
    AND "status" IN ('PENDING', 'APPROVED', 'PROCESSING');
