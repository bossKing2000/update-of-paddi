/**
 * Batch 1D.45 — regression coverage for the test-number generator used by the
 * real-Redis OTP suite.
 *
 * The prepared integration suite could not be executed in this environment
 * (no Redis server exists), but its number generator had two defects that are
 * provable WITHOUT Redis, so they are proven here:
 *
 *   1. The old inline generator produced `+120255501001`, which
 *      `normalizePhoneNumber()` rejects. Every `requestOtp()` in that suite
 *      would have thrown `InvalidPhoneNumberError` before touching Redis.
 *   2. Its counter restarted each run and the `RUN` constant beside it was
 *      dead code, so two runs shared Redis keys — and production keys are
 *      `otp:<kind>:<E.164>`, meaning one run's cleanup could delete another
 *      run's data.
 *
 * These tests run in the unit suite and therefore DO execute. They do NOT
 * prove the Lua scripts work; that remains unverified until the integration
 * suite can run against a real Redis.
 */
import { normalizePhoneNumber } from "../../src/utils/phone";
import {
  createRunPhoneNumberFactory,
  runScopedTestIp,
  isRunScopedTestPhone,
  runEntropy,
  mix32,
  SUBSCRIBER_SPACE,
  RESERVED_PER_RUN,
  BLOCK_COUNT,
  TEST_IP_SPACE,
} from "../helpers/otpTestPhoneNumbers";

describe("otp test phone numbers are accepted by the production normalizer", () => {
  it("every generated number passes normalizePhoneNumber", () => {
    const next = createRunPhoneNumberFactory(1_700_000_000_000);
    for (let i = 0; i < RESERVED_PER_RUN; i++) {
      const phone = next();
      // The defect this replaces: normalizePhoneNumber used to throw here.
      expect(() => normalizePhoneNumber(phone)).not.toThrow();
      expect(normalizePhoneNumber(phone)).toBe(phone);
    }
  });

  it("the shape is +23480 followed by eight digits", () => {
    const next = createRunPhoneNumberFactory(42);
    expect(next()).toMatch(/^\+23480\d{8}$/);
  });

  it("rejects the number the old generator produced", () => {
    // Direct proof of the defect: this exact string was generated by the
    // prepared suite and is not a usable phone number.
    const oldGenerated = "+120255501001";
    expect(oldGenerated).not.toMatch(/^\+23480\d{8}$/);
    expect(() => normalizePhoneNumber(oldGenerated)).toThrow();
  });

  it("isRunScopedTestPhone agrees with the real normalizer", () => {
    const next = createRunPhoneNumberFactory(7);
    expect(isRunScopedTestPhone(next())).toBe(true);
    expect(isRunScopedTestPhone("+120255501001")).toBe(false);
    expect(isRunScopedTestPhone("not-a-number")).toBe(false);
  });
});

describe("otp test phone numbers are unique within a run", () => {
  it("a full run produces no duplicates", () => {
    const next = createRunPhoneNumberFactory(1_700_000_000_001);
    const seen = new Set<string>();
    for (let i = 0; i < RESERVED_PER_RUN; i++) seen.add(next());
    expect(seen.size).toBe(RESERVED_PER_RUN);
  });

  it("refuses to overrun its reserved block rather than colliding silently", () => {
    const next = createRunPhoneNumberFactory(1_700_000_000_002);
    for (let i = 0; i < RESERVED_PER_RUN; i++) next();
    expect(() => next()).toThrow(/ran out of reserved phone numbers/);
  });
});

describe("otp test phone numbers are isolated between runs", () => {
  it("two runs starting a second apart produce disjoint sets", () => {
    const a = createRunPhoneNumberFactory(1_700_000_000_000);
    const b = createRunPhoneNumberFactory(1_700_000_001_000);
    const setA = new Set<string>();
    const setB = new Set<string>();
    for (let i = 0; i < RESERVED_PER_RUN; i++) {
      setA.add(a());
      setB.add(b());
    }
    // Disjoint keys matter: production keys are otp:<kind>:<E.164>, so a
    // shared number means shared keys and cross-run deletion.
    for (const phone of setA) expect(setB.has(phone)).toBe(false);
  });

  it("is reproducible when the same entropy is supplied", () => {
    // Determinism on demand, which is what made the old suite useful for
    // debugging; randomness only enters through the default entropy.
    const a = createRunPhoneNumberFactory(1_700_000_000_000);
    const b = createRunPhoneNumberFactory(1_700_000_000_000);
    expect(a()).toBe(b());
  });

  it("Batch 1D.46: runs ~100s apart no longer alias onto the same block", () => {
    // The old allocation was `seed % BLOCK_COUNT`, which is periodic: any two
    // runs BLOCK_COUNT ms apart (~99.9 s) shared every Redis key, and one
    // run's cleanup deleted the other's data.
    const base = 1_700_000_000_000;
    const first = createRunPhoneNumberFactory(base)();
    for (const deltaMs of [BLOCK_COUNT, BLOCK_COUNT * 2, BLOCK_COUNT * 5]) {
      const other = createRunPhoneNumberFactory(base + deltaMs)();
      expect(other).not.toBe(first);
    }
  });

  it("Batch 1D.46: nearby timestamps scatter instead of stepping by one", () => {
    const base = 1_700_000_000_000;
    const seen = new Set<string>();
    for (let ms = 0; ms < 50; ms++) {
      seen.add(createRunPhoneNumberFactory(base + ms)());
    }
    // A `seed % n` allocation would still be 50 distinct values here, so the
    // meaningful assertion is that the values are scattered across the
    // space rather than consecutive.
    const offsets = [...seen].map((p) => Number(p.slice("+23480".length)));
    const gaps = offsets.slice(1).map((v, i) => Math.abs(v - offsets[i])).sort((a, b) => a - b);
    expect(gaps[0]).toBeGreaterThan(1);
  });

  it("every generated value stays inside the verified space", () => {
    const next = createRunPhoneNumberFactory(SUBSCRIBER_SPACE * 3);
    for (let i = 0; i < RESERVED_PER_RUN; i++) {
      const subscriber = Number(next().slice("+23480".length));
      expect(subscriber).toBeGreaterThanOrEqual(0);
      expect(subscriber).toBeLessThan(SUBSCRIBER_SPACE);
    }
  });

  it("gives two runs a different client IP so IP counters do not collide", () => {
    const base = 1_700_000_000_000;
    const a = runScopedTestIp(base);
    const b = runScopedTestIp(base + 3_000);
    expect(a).toBeDefined();
    expect(a).not.toBe(b);
  });

  it("Batch 1D.46: runs 254ms apart no longer share an IP", () => {
    // The old `1 + (seed % 254)` allocation aliased every 254 ms, and the
    // suite asserts EXACT values on the shared otp:rl:ip counter.
    const base = 1_700_000_000_000;
    const first = runScopedTestIp(base);
    for (const deltaMs of [254, 508, 762, 1000]) {
      expect(runScopedTestIp(base + deltaMs)).not.toBe(first);
    }
  });

  it("Batch 1D.46: every generated IP is a usable documentation address", () => {
    const base = 1_700_000_000_000;
    for (let i = 0; i < 200; i++) {
      expect(runScopedTestIp(base + i)).toMatch(
        /^(192\.0\.2|198\.51\.100|203\.0\.113)\.(?:[1-9]\d?|[1-9]\d|1\d\d|2[0-4]\d|25[0-4])$/,
      );
    }
    expect(TEST_IP_SPACE).toBe(762);
  });

  it("Batch 1D.46: default entropy differs between consecutive calls", () => {
    const a = runEntropy();
    const b = runEntropy();
    expect(typeof a).toBe("number");
    // Wall-clock plus a random draw; a collision is possible but vanishingly
    // unlikely, and equal values would mean the random term was lost.
    expect(a === b).toBe(false);
  });

  it("mix32 spreads a small range instead of preserving adjacency", () => {
    const base = 1_700_000_000_000;
    const mixed = [0, 1, 2, 3, 4].map((i) => mix32(base + i) % BLOCK_COUNT);
    expect(new Set(mixed).size).toBe(5);
    const deltas = mixed.slice(1).map((v, i) => Math.abs(v - mixed[i]));
    expect(Math.min(...deltas)).toBeGreaterThan(1);
  });
});